typedef struct { DK3VM *vm; int order; } ResourceHost;
static void dispose_counter(void *userdata, void *payload) {
    ResourceHost *host = (ResourceHost *)userdata;
    host->order = host->order * 10 + *(int *)payload;
    assert(dk3_collect(host->vm) == DK3_BUSY && dk3_close_resources(host->vm) == DK3_BUSY);
}
static void resource_lifecycle(void) {
    DK3VM *vm = dk3_create(NULL); ResourceHost host = {vm, 0}; int one = 1, two = 2, three = 3;
    DK3Resource descriptor; dk3_resource_init(&descriptor);
    descriptor.type_name = "Counter"; descriptor.payload = &one; descriptor.userdata = &host; descriptor.dispose = dispose_counter;
    DK3Value *first = NULL, *second = NULL, *third = NULL; void *payload = NULL; int closed = 1; DK3Type type;
    descriptor.abi_version++; assert(dk3_resource(vm, &descriptor, &first) == DK3_INVALID && first == NULL && host.order == 0); descriptor.abi_version--;
    assert(dk3_resource(vm, &descriptor, &first) == DK3_OK);
    assert(dk3_get_type(first, &type) == DK3_OK && type == DK3_RESOURCE);
    assert(dk3_resource_get(first, "Counter", &payload) == DK3_OK && payload == &one);
    assert(dk3_resource_get(first, "Other", &payload) == DK3_INVALID && payload == NULL);
    assert(dk3_define_native(vm, "resourceValue", "() -> Resource", return_handle, first) == DK3_OK);
    assert(dk3_eval(vm, "let resourceMeta: Resource = resourceValue()\nlet beforeClosed: Bool = resourceMeta.closed\nlet resourceTag: String = resourceMeta.type_name\nlet resourceMembers = Reflection.members(resourceMeta)\nGC.collect()", "resource-metadata.k3") == DK3_OK);
    assert(dk3_eval(vm, "resourceMeta.closed = true", "readonly-resource.k3") == DK3_ERROR);
    assert(dk3_resource_closed(first, &closed) == DK3_OK && closed == 0);
    DK3VM *foreign = dk3_create(NULL); descriptor.parent = first;
    assert(dk3_resource(foreign, &descriptor, &second) == DK3_INVALID && second == NULL);
    assert(dk3_destroy(foreign) == DK3_OK);
    descriptor.parent = first;
    descriptor.payload = &two; assert(dk3_resource(vm, &descriptor, &second) == DK3_OK);
    assert(dk3_resource_close(first) == DK3_BUSY && host.order == 0);
    assert(dk3_resource_close(second) == DK3_OK && host.order == 2);
    descriptor.parent = NULL;
    descriptor.payload = &three; assert(dk3_resource(vm, &descriptor, &third) == DK3_OK);
    assert(dk3_release(third) == DK3_OK && dk3_collect(vm) == DK3_OK && host.order == 2);
    assert(dk3_resource_closed(first, &closed) == DK3_OK && closed == 0);
    assert(dk3_resource_close(first) == DK3_OK && dk3_resource_close(first) == DK3_OK && host.order == 21);
    assert(dk3_resource_get(first, "Counter", &payload) == DK3_ERROR && payload == NULL);
    descriptor.parent = first;
    assert(dk3_resource(vm, &descriptor, &third) == DK3_ERROR && third == NULL && host.order == 21);
    assert(dk3_close_resources(vm) == DK3_OK && host.order == 213);
    assert(dk3_resource_closed(second, &closed) == DK3_OK && closed == 1);
    assert(dk3_destroy(vm) == DK3_OK && host.order == 213);
}
static void dispose_budgeted(void *userdata, void *payload) {
    assert(userdata == payload); ++*(int *)userdata;
}
static void native_limits(void) {
    DK3Config config; dk3_config_init(&config); config.object_limit = 256;
    DK3VM *vm = dk3_create(&config); assert(vm);
    int disposed = 0; DK3Resource descriptor; dk3_resource_init(&descriptor);
    descriptor.type_name = "Budgeted"; descriptor.payload = &disposed; descriptor.userdata = &disposed; descriptor.dispose = dispose_budgeted;
    DK3Value *value = NULL;
    for (size_t index = 0; index < config.object_limit; index++) {
        assert(dk3_resource(vm, &descriptor, &value) == DK3_OK && dk3_release(value) == DK3_OK);
        assert(dk3_collect(vm) == DK3_OK && disposed == 0);
    }
    assert(dk3_resource(vm, &descriptor, &value) == DK3_LIMIT && value == NULL && disposed == 0);
    assert(dk3_close_resources(vm) == DK3_OK && disposed == (int)config.object_limit);
    assert(dk3_resource(vm, &descriptor, &value) == DK3_OK && dk3_release(value) == DK3_OK);
    DK3NativeExport exports[256]; char names[256][32]; int64_t increment = 1;
    for (size_t index = 0; index < 256; index++) {
        snprintf(names[index], sizeof(names[index]), "entry%zu", index);
        exports[index] = (DK3NativeExport){names[index], "(number: Int) -> Int", add, &increment, NULL};
    }
    DK3NativeModule module; dk3_module_init(&module);
    module.name = "Limited"; module.count = 256; module.exports = exports;
    assert(dk3_register_module(vm, &module) == DK3_LIMIT);
    assert(dk3_get(vm, "Limited", &value) == DK3_ERROR && value == NULL);
    assert(dk3_collect(vm) == DK3_OK);
    module.count = 1; assert(dk3_register_module(vm, &module) == DK3_OK);
    assert(dk3_destroy(vm) == DK3_OK && disposed == (int)config.object_limit + 1);
}
static DK3Status read_file(void *userdata, const char *path, size_t limit, const char **bytes, size_t *length) {
    FileHost *host = (FileHost *)userdata; host->reads++;
    assert(dk3_collect(host->vm) == DK3_BUSY && dk3_set_files(host->vm, NULL) == DK3_BUSY);
    if (strcmp(path, "missing") == 0) return DK3_ERROR;
    if (strcmp(path, "large") == 0) { *bytes = "x"; *length = limit + 1; return DK3_OK; }
    if (strcmp(path, "invalid") == 0) { *bytes = NULL; *length = 1; return DK3_OK; }
    if (strcmp(path, "empty") == 0) { *bytes = NULL; *length = 0; return DK3_OK; }
    *bytes = "host\0data"; *length = 9; return DK3_OK;
}
static DK3Status file_size(void *userdata, const char *path, int *exists, uint64_t *size) {
    FileHost *host = (FileHost *)userdata;
    assert(dk3_collect(host->vm) == DK3_BUSY);
    *exists = strcmp(path, "missing") != 0; *size = strcmp(path, "empty") == 0 ? 0 : 9;
    if (strcmp(path, "invalid") == 0) *exists = 2;
    return DK3_OK;
}

