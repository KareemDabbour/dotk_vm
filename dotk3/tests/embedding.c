    assert(dk3_native_value_string(call, key, &bytes, &byteLength) == DK3_OK && byteLength == 4 && memcmp(bytes, "rows", 4) == 0);
    assert(dk3_native_release(call, key) == DK3_OK && dk3_native_release(call, item) == DK3_OK);
