static DK3Status add(DK3Call *call, void *userdata) {
    int64_t number;
    if (dk3_native_count(call) != 1 || dk3_native_int(call, 0, &number) != DK3_OK)
        return dk3_native_error(call, "Expected one Int");
    return dk3_native_return_int(call, number + *(int64_t *)userdata);
}

static DK3Status cleanup(DK3Call *call, void *userdata) {
    int64_t number;
    assert(dk3_native_int(call, 0, &number) == DK3_OK);
    *(int *)userdata = *(int *)userdata * 10 + (int)number;
    assert(dk3_collect(dk3_native_vm(call)) == DK3_BUSY);
    return dk3_native_return_int(call, 0);
}
static DK3Status scalar_echo(DK3Call *call, void *userdata) {
    (void)userdata; int boolean; double floating; const char *bytes; size_t length;
    assert(dk3_native_count(call) == 1 && dk3_collect(dk3_native_vm(call)) == DK3_BUSY);
    if (dk3_native_bool(call, 0, &boolean) == DK3_OK) return dk3_native_return_bool(call, boolean);
    if (dk3_native_float(call, 0, &floating) == DK3_OK) return dk3_native_return_float(call, floating);
    if (dk3_native_string(call, 0, &bytes, &length) == DK3_OK) return dk3_native_return_string(call, bytes, length);
    if (dk3_native_bytes(call, 0, &bytes, &length) == DK3_OK) return dk3_native_return_bytes(call, bytes, length);
    return dk3_native_return_null(call);
}
static DK3Status return_handle(DK3Call *call, void *userdata) {
    return dk3_native_return_value(call, (const DK3Value *)userdata);
}
